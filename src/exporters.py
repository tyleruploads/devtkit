"""
exporters.py
-----

This file contains functions that convert and export raw information into file outputs.
"""

import csv  # To save the followers table to CSV
import json  # To save the followers table to JSON

from datetime import datetime
from typing import Any  # To help return hints


def md_header() -> str:
    """Makes the header for a Markdown output of followers

    Returns:
      str: The Markdown string for the header
    """
    # Makes the header for the top of the markdown file
    # This does not require any variables passed
    return """
# devtkit  \n
> Generated by [devtkit](https://github.com/tyleruploads/devtkit).
> It is not limited to Markdown files; it supports Markdown, JSON, and CSV exports
"""


def md_profile_table(user_info: dict[str, Any]) -> str:
    """Makes the profile table for the users account in a Markdown output

    Args:
      user_info: dict[str:
      Any]: The information about the user to be put in the table

    Returns:
          str: The Markdown string for the profile table
    """
    return (
        f"### Profile: {user_info['name']}\n\n"
        f"| Attribute | Details |\n"
        f"| :--- | :--- |\n"
        f"| **Name** | {user_info['name']} |\n"
        f"| **Username** | [{user_info['username']}]"
        f"(https://dev.to/{user_info['username']}) |\n"
        f"| Summary | {user_info['summary']} |\n"
        f"| Location | {user_info['location']} |\n"
        f"| Joined At | {user_info['joined_at']} |\n"
        f"| User ID | [{user_info['id']}]"
        f"(https://dev.to/api/users/{user_info['id']}) |\n"
        f"| **Profile Picture** | <img src='{user_info['profile_image']}' width='100' alt='Profile'>  |\n"
    )


def md_followers_info_block(followers_list: list[dict]) -> str:
    """Makes the info block for a followers export in a Markdown output

    Args:
      followers_list: list[dict]: A list of dictionaries containing information about the users followers

    Returns:
      str: The Markdown string for the information block
    """
    # This makes a block to put in the Markdown output
    # This block contains information such as the date and follower count

    # Get the time
    now = datetime.now()
    # Example: Thursday, June 18, 2026
    formatted_date = now.strftime("%A, %B %d, %Y")

    # Get follower count
    follower_count = len(followers_list)

    return (
        f"> This was generated on {formatted_date}  \n"
        f"> {follower_count} followers were found  \n\n"
    )


def md_followers_table(followers_list: list[dict]) -> str:
    """Makes the table of all the users followers in a Markdown output

    Args:
      followers_list: list[dict]: A list of dictionaries containing information about the users followers

    Returns:
      str: The Markdown string for the followers table
    """
    # Check if the user has no followers
    if len(followers_list) == 0:
        # Return a notice that there are no followers
        return (
            "> NOTICE: The user that the provided API Key"
            "belongs to does not appear to have any followers"
            "There are no followers to make a table with"
        )

        # End of if statement

    users_md_part = """
| Index | Username | Name | Followed At | User ID |
| :--- | :--- | :--- | :--- | :--- |
"""

    for idx, follower in enumerate(followers_list):
        # Define variables
        name = follower["name"]
        username = follower["username"]
        user_id = follower["user_id"]

        # created_at is follow time, not account creation time
        followed_at = follower["created_at"]

        user_md_part = (
            f"| {idx} | [@{username}](https://dev.to/{username}) | {name} |"
            f"{followed_at} | [{user_id}](https://dev.to/api/users/{user_id}) |  \n"
        )
        users_md_part += user_md_part

    return users_md_part


def md_followers_make(followers_list: list[dict], self_info: dict[str, Any]) -> str:
    """Makes a Markdown string

    Args:
      followers_list: list[dict]: A list of dictionaries containing information about the users followers
      self_info: dict[str:
      Any]: A dictionary containing information about the user

    Returns:
      str: The entire Markdown string
    """
    md_string = ""
    md_string += md_header()
    md_string += md_profile_table(self_info)
    md_string += md_followers_info_block(followers_list)
    md_string += md_followers_table(followers_list)
    return md_string


def md_articles_info_block(articles: list[dict]) -> str:
    """Makes the info block for an article export in a Markdown output

    Args:
      followers_list: list[dict]: A list of dictionaries containing information about the users followers

    Returns:
      str: The Markdown string for the information block
    """
    # This makes a block to put in the Markdown output
    # This block contains information such as the date and follower count

    # Get the time
    now = datetime.now()
    # Example: Thursday, June 18, 2026
    formatted_date = now.strftime("%A, %B %d, %Y")

    article_count = len(articles)

    return (
        f'<div align="center">\n\n'
        f"| **Total Articles** | **Generated On** |\n"
        f"| :---: | :---: |\n"
        f"| {article_count} | {formatted_date} |\n\n"
        f"</div>\n\n"
        f"---\n\n"
    )


def md_articles_make(articles: list[dict], self_info: dict[str, Any]) -> str:
    if not articles:
        raise ValueError("No articles found")

    md_string = f"# Articles Authored by {articles[0]['user']['name']}\n"
    md_string += "> Generated by [devtkit](https://github.com/tyleruploads/devtkit)\n"
    md_string += md_articles_info_block(self_info)

    for article in articles:
        if article.get("cover_image"):
            md_string += f'<p align="center"><img src="{article["cover_image"]}" alt="Article Cover" width="100%" style="border-radius: 8px;" /></p>\n\n'

        md_string += "## [" + article["title"] + "](" + article["url"] + ")\n\n"
        md_string += f"> **Published:** {article['readable_publish_date']} ({article['published_timestamp']}) &nbsp;&nbsp;|&nbsp;&nbsp; {article['reading_time_minutes']} minute read\n\n"
        md_string += f"Tags: {article['tag_list']}\n\n"
        md_string += f"{article['reading_time_minutes']} minute read\n"
        md_string += (
            f"Created by: {article['user']['name']} ({article['user']['username']})\n\n"
        )
        md_string += article["body_markdown"] + "\n\n\n"
        md_string += "<br>\n\n---\n<br>\n\n"
    return md_string


def save_files(
    dict_list: list[dict],
    formats_and_paths: dict[str, str],
    self_info: dict[str, Any] = None,
    export_type: str = "Followers",
) -> None:
    """Saves files at specified locations in Markdown, JSON, or CSV outputs

    Args:
      followers_list: list[dict]: A list of dictionaries containing information about the users followers
      formats_and_paths: dict[str:
      str]: A list of file formats and its associated save path
      self_info: dict[str:
      Any]:  (Default value = None): A dictionary of information about the user
    """
    for mode, path in formats_and_paths.items():
        if mode == "markdown":
            with open(path, "w") as f:
                if export_type == "Followers":
                    f.write(md_followers_make(dict_list, self_info))
                else:
                    f.write(md_articles_make(dict_list, self_info))

            print(f"Saved in the Markdown file format to {path}")
        elif mode == "json":
            with open(path, "w") as f:
                json.dump(dict_list, f, indent=4)

            print(f"Saved in the JSON file format to {path}")
        elif mode == "csv":
            headers = dict_list[0].keys()

            with open(path, "w", newline="", encoding="utf-8") as f:
                writer = csv.DictWriter(f, fieldnames=headers)

                writer.writeheader()
                writer.writerows(dict_list)

            print(f"Saved in the CSV file format to {path}")
        else:
            raise ValueError(
                f"The mode value of {mode} is not supported"
                "in the save_followers_table function.",
            )
